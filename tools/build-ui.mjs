import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';

await build({
  entryPoints: ['site/ui-entry.js'],
  outfile: 'site/assets/ui.js',
  bundle: true,
  minify: true,
  format: 'esm',
  target: ['es2022'],
  legalComments: 'eof',
});
const packages = ['@santi020k/lumen-elements', '@santi020k/lumen-core', '@santi020k/lumen'];
let notices = 'Bundled UI dependencies. Generated by npm run build:ui.\n';
for (const name of packages) {
  const root = `node_modules/${name}`;
  const metadata = JSON.parse(await readFile(`${root}/package.json`, 'utf8'));
  notices += `\n${name} ${metadata.version} (${metadata.license})\n`;
  notices += await readFile(`${root}/LICENSE`, 'utf8');
}
await writeFile('site/assets/LICENSES.txt', notices);
console.log('Built local Lumen CSS/JS and license notices. No runtime CDN.');
